    def load_settings(self):
        for name in ("MASS", "TARGET_ALTITUDE", "BASE_CD", "MOTOR_MIN", "MOTOR_MAX"):
            self.fields[name].set(macro(name))
        self.fields["TEMP_F"].set("68.0"); self.fields["HUMIDITY"].set("55.0"); self.fields["PRESSURE"].set("1015.0")

    def refresh_ports(self):
        ports = board_ports(); self.port_box["values"] = [f"{d} | {t[:70]}" for d, t in ports]
        if ports: self.port_box.current(0); self.log(f"Detected Airbrakes-compatible board on {ports[0][0]}.")
        else: self.log("No Airbrakes board detected. Connect it over USB and press Refresh.")

    def selected_port(self):
        value = self.port_var.get()
        return value.split(" | ", 1)[0] if value else None

    def connect(self):
        if serial is None: return messagebox.showerror("Missing dependency", "Install the app dependencies first: pyserial and matplotlib.")
        port = self.selected_port()
        if not port: return messagebox.showwarning("No board", "Connect the flight computer and press Refresh.")
        try:
            with serial.Serial(port, 115200, timeout=1): pass
            self.port = port; self.connection_label.configure(text=f"Connected: {port}", foreground="#176b3a"); self.log(f"Connected to {port}."); self.list_flights()
        except Exception as exc: messagebox.showerror("Connection failed", str(exc))

    def open_serial(self):
        if serial is None: raise RuntimeError("pyserial is not installed")
        port = self.port or self.selected_port()
        if not port: raise RuntimeError("No flight computer connected")
        return serial.Serial(port, 115200, timeout=1)

    def command(self, ser, command, end="FLASH:END"):
        ser.reset_input_buffer(); ser.write((command + "\n").encode()); lines = []
        deadline = time.time() + 3
        while time.time() < deadline:
            line = ser.readline().decode(errors="ignore").strip()
            if line: lines.append(line)
            if line == end: break
        return lines

    def list_flights(self):
        try:
            with self.open_serial() as ser: lines = self.command(ser, "LIST")
            self.flight_rows = [line for line in lines if line.startswith("FLASH:FLIGHT:")]
            self.flight_list.delete(0, "end")
            for row in self.flight_rows: self.flight_list.insert("end", row.replace("FLASH:FLIGHT:", ""))
            self.log(f"Found {len(self.flight_rows)} flight(s) on the board.")
        except Exception as exc: self.log(f"Could not list flights: {exc}")

    def flight_number(self):
        index = self.flight_list.curselection()
        if not index: return None
        match = re.search(r"flight_(\d+)", self.flight_rows[index[0]])
        return int(match.group(1)) if match else None

    def download(self, number, delete=False):
        FLIGHT_DIR.mkdir(exist_ok=True)
        with self.open_serial() as ser:
            ser.reset_input_buffer(); ser.write(f"GET {number}\n".encode()); data = bytearray(); started = False; deadline = time.time() + 8
            while time.time() < deadline:
                chunk = ser.read(ser.in_waiting or 1)
                if not chunk: continue
                if not started:
                    marker = chunk.find(b"FLASH:DATA_START\n")
                    if marker < 0: continue
                    chunk = chunk[marker + len(b"FLASH:DATA_START\n"):]; started = True
                end = chunk.find(b"FLASH:END")
                if end >= 0: data.extend(chunk[:end]); break
                data.extend(chunk); deadline = time.time() + 5
            if len(data) < RECORD_SIZE: raise RuntimeError("The board returned no complete flight records")
            stamp = datetime.now().strftime("%Y%m%d_%H%M%S"); path = FLIGHT_DIR / f"flight_{number}_{stamp}.csv"
            with path.open("w", newline="", encoding="utf-8") as output:
                writer = csv.writer(output); writer.writerow(["time_s", "altitude_m", "velocity_ms", "accel_bias_ms2", "raw_accel_ms2", "raw_baro_m", "motor_pos", "motor_vel", "motor_cmd_pos", "roll_rad", "pitch_rad", "yaw_rad", "Cd", "desired_Cd", "motor_current_A", "state", "axis_error"])
                for offset in range(0, len(data) - RECORD_SIZE + 1, RECORD_SIZE):
                    values = struct.unpack(RECORD_FORMAT, data[offset:offset + RECORD_SIZE]); state = STATE_NAMES[values[15]] if values[15] < len(STATE_NAMES) else f"UNKNOWN({values[15]})"
                    writer.writerow([values[0] / 1000.0, *[f"{v:.6f}" for v in values[1:15]], state, values[16]])
            if delete: ser.reset_input_buffer(); ser.write(f"DELETE {number}\n".encode())
        return path

    def download_selected(self):
        number = self.flight_number()
        if number is None: return messagebox.showinfo("Select a flight", "Select a flight first.")
        try: path = self.download(number); self.refresh_files(); self.log(f"Saved {path.name}.")
        except Exception as exc: messagebox.showerror("Download failed", str(exc))

    def download_all(self):
        try:
            with self.open_serial() as ser: lines = self.command(ser, "LIST")
            nums = [int(m.group(1)) for line in lines if "[ACTIVE]" not in line for m in [re.search(r"flight_(\d+)", line)] if m]
            for number in nums: self.download(number, delete=True)
            self.refresh_files(); self.log(f"Downloaded {len(nums)} flight(s) and cleared confirmed copies from the board.")
        except Exception as exc: messagebox.showerror("Download failed", str(exc))

    def delete_selected(self):
        number = self.flight_number()
        if number is None or not messagebox.askyesno("Delete flight", f"Delete flight {number} from the board? Download it first if you need it."): return
        try:
            with self.open_serial() as ser: self.command(ser, f"DELETE {number}", end="FLASH:DELETED")
            self.list_flights()
        except Exception as exc: messagebox.showerror("Delete failed", str(exc))

    def save_settings(self):
        try:
            mass = float(self.fields["MASS"].get()); temp = float(self.fields["TEMP_F"].get()); humidity = float(self.fields["HUMIDITY"].get()); pressure = float(self.fields["PRESSURE"].get())
            rho = density(temp, humidity, pressure); update_macro("MASS", f"{mass:.6f}"); update_macro("TARGET_ALTITUDE", f"{float(self.fields['TARGET_ALTITUDE'].get()):.3f}"); update_macro("BASE_CD", f"{float(self.fields['BASE_CD'].get()):.4f}"); update_macro("MOTOR_MIN", f"{float(self.fields['MOTOR_MIN'].get()):.3f}"); update_macro("MOTOR_MAX", f"{float(self.fields['MOTOR_MAX'].get()):.3f}"); update_macro("RHO", f"{rho:.6f}")
            write_coast_table(mass, rho); self.log(f"Saved launch settings. Air density: {rho:.4f} kg/m^3. Coast table regenerated.")
        except Exception as exc: messagebox.showerror("Settings error", str(exc))

    def generate(self): self.save_settings()

    def run_pio(self, target):
        pio = shutil.which("pio") or str(ROOT / ".pio" / "penv" / "Scripts" / "pio.exe")
        if not Path(pio).exists() and not shutil.which("pio"): return messagebox.showerror("PlatformIO not found", "Install PlatformIO Core once. After that this app handles builds and uploads without VS Code.")
        self.log(f"Running PlatformIO {target}...")
        def worker():
            try:
                args = [pio, "run", "-t", target] if target != "run" else [pio, "run"]
                if target == "upload": args += ["--upload-port", self.selected_port() or self.port]
                result = subprocess.run(args, cwd=ROOT, capture_output=True, text=True, timeout=240)
                self.after(0, lambda: self.log((result.stdout + result.stderr)[-4000:] if result.returncode else f"PlatformIO {target} completed successfully."))
            except Exception as exc: self.after(0, lambda: self.log(f"PlatformIO failed: {exc}"))
        threading.Thread(target=worker, daemon=True).start()

    def flash(self):
        if not (self.port or self.selected_port()): return messagebox.showwarning("No board", "Connect the flight computer before flashing.")
        self.save_settings(); self.run_pio("upload")

    def refresh_files(self):
        FLIGHT_DIR.mkdir(exist_ok=True); files = sorted(FLIGHT_DIR.glob("flight_*.csv"), reverse=True); self.file_box["values"] = [str(p) for p in files]
        if files: self.file_box.current(0)

    def plot_selected(self):
        if Figure is None: return messagebox.showerror("Missing dependency", "Install matplotlib to use flight plots.")
        path = Path(self.file_var.get())
        if not path.exists(): return
        with path.open(newline="", encoding="utf-8") as source: rows = list(csv.DictReader(source))
        if not rows: return
        def col(name): return [float(row[name]) for row in rows]
        for child in self.plot_frame.winfo_children(): child.destroy()
        fig = Figure(figsize=(10, 6), dpi=95); axes = fig.subplots(3, 2); t = col("time_s")
        charts = [("altitude_m", "Altitude", "m"), ("velocity_ms", "Velocity", "m/s"), ("raw_accel_ms2", "Acceleration", "m/s²"), ("motor_pos", "Motor position", "position"), ("Cd", "Cd", ""), ("desired_Cd", "Predicted/desired Cd", "")]
        for axis, (name, title, unit) in zip(axes.flat, charts): axis.plot(t, col(name), linewidth=1.2, label=name); axis.set_title(title); axis.set_xlabel("Time (s)"); axis.set_ylabel(unit); axis.grid(True, alpha=.25); axis.legend(loc="best", fontsize=8)
        fig.tight_layout(); canvas = FigureCanvasTkAgg(fig, master=self.plot_frame); canvas.draw(); canvas.get_tk_widget().pack(fill="both", expand=True)


