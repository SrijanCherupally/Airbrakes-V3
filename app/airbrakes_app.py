def density(temp_f, humidity, pressure_hpa):
    temp_c = (temp_f - 32.0) * 5.0 / 9.0
    temp_k = temp_c + 273.15
    rh = max(0.0, min(100.0, humidity)) / 100.0
    pressure_pa = pressure_hpa * 100.0
    sat = 610.94 * math.exp((17.625 * temp_c) / (temp_c + 243.04))
    vapor = rh * sat
    return (pressure_pa - vapor) / (287.05 * temp_k) + vapor / (461.495 * temp_k)


def coast_height(velocity, cd, mass, rho):
    vel = velocity
    height = 0.0
    dt = 0.001
    for _ in range(20000):
        if vel <= 0:
            break
        accel = (-0.5 * rho * ((math.pi * (0.066 ** 2)) / 4.0) * cd * vel * abs(vel) - mass * 9.80665) / mass
        vel += accel * dt
        height += vel * dt
    return max(0.0, height)


def write_coast_table(mass, rho):
    n_vel, n_cd = 20, 20
    vel_min, vel_max, cd_min, cd_max = 0.0, 80.0, 0.0, 6.0
    velocities = [vel_min + (vel_max - vel_min) * i / (n_vel - 1) for i in range(n_vel)]
    cds = [cd_min + (cd_max - cd_min) * i / (n_cd - 1) for i in range(n_cd)]
    table = [[coast_height(v, cd, mass, rho) for cd in cds] for v in velocities]
    lines = [
        "#ifndef COAST_TABLE_H", "#define COAST_TABLE_H", "",
        "// Auto-generated by Airbrakes V3 Ground Station.",
        f"// {n_vel}x{n_cd} table, vel {vel_min:.1f}-{vel_max:.1f} m/s, Cd {cd_min:.2f}-{cd_max:.2f}",
        "", f"constexpr int COAST_N_VEL = {n_vel};", f"constexpr int COAST_N_CD = {n_cd};", "",
        f"constexpr float COAST_VEL_MIN = {vel_min:.1f}f;",
        f"constexpr float COAST_VEL_MAX = {vel_max:.1f}f;",
        f"constexpr float COAST_VEL_STEP = {(vel_max - vel_min) / (n_vel - 1):.10f}f;",
        f"constexpr float COAST_CD_MIN = {cd_min:.2f}f;", f"constexpr float COAST_CD_MAX = {cd_max:.2f}f;",
        f"constexpr float COAST_CD_STEP = {(cd_max - cd_min) / (n_cd - 1):.10f}f;", "",
        f"constexpr float COAST_ALTITUDE_TABLE[{n_vel}][{n_cd}] = {{",
    ]
    lines += ["    {" + ", ".join(f"{value:.6f}f" for value in row) + "}," for row in table]
    lines += ["};", "", "#endif  // COAST_TABLE_H", ""]
    COAST_HEADER.write_text("\n".join(lines), encoding="ascii")
    return velocities, cds, table


def update_macro(name, value, suffix="f"):
    text = CONFIG.read_text(encoding="utf-8")
    pattern = rf"^#define\s+{name}\s+.*$"
    updated, count = re.subn(pattern, f"#define {name} {value}{suffix}", text, flags=re.MULTILINE)
    if not count:
        raise ValueError(f"Could not find {name} in include/config.h")
    CONFIG.write_text(updated, encoding="ascii")


def macro(name, default=""):
    match = re.search(rf"^#define\s+{name}\s+([^\s/]+)", CONFIG.read_text(encoding="utf-8"), re.MULTILINE)
    return match.group(1).rstrip("f") if match else default


def board_ports():
    if list_ports is None:
        return []
    ports = []
    for port in list_ports.comports():
        text = " ".join(str(x or "") for x in (port.device, port.description, port.manufacturer, port.product))
        score = 0 if any(x.lower() in text.lower() for x in ("srijan", "airbrakes v3")) else 1
        if any(x.lower() in text.lower() for x in ("pico", "rp2040", "rp2350", "airbrakes", "srijan")):
            ports.insert(0 if score == 0 else len(ports), (port.device, text))
    return ports


